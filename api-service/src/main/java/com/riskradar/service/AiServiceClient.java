package com.riskradar.service;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.web.reactive.function.client.WebClient;
import reactor.core.publisher.Mono;

import java.time.Duration;
import java.util.Map;

@Service
public class AiServiceClient {

    private final WebClient webClient;

    public AiServiceClient(
            WebClient.Builder builder,
            @Value("${riskradar.ai-service.url:http://localhost:8000}") String aiServiceUrl) {
        this.webClient = builder.baseUrl(aiServiceUrl).build();
    }

    @SuppressWarnings("unchecked")
    public Mono<Map<String, Object>> analyzeText(String text, String company) {
        return webClient.post()
                .uri("/analyze")
                .bodyValue(Map.of("text", text, "company", company))
                .retrieve()
                .bodyToMono(Map.class)
                .map(m -> (Map<String, Object>) m)
                .timeout(Duration.ofSeconds(6))
                .onErrorResume(e -> Mono.just(Map.of(
                        "error", "AI microservice unreachable",
                        "summary", "Rule-based analysis pending. AI service at port 8000 unreachable: " + e.getMessage(),
                        "is_high_risk", false,
                        "risk_score_delta", 0.0
                )));
    }

    @SuppressWarnings("unchecked")
    public Mono<Map<String, Object>> getExplanation(String company) {
        return webClient.get()
                .uri("/explain-json/{company}", company)
                .retrieve()
                .bodyToMono(Map.class)
                .map(m -> (Map<String, Object>) m)
                .timeout(Duration.ofSeconds(12))
                .onErrorResume(e -> Mono.just(Map.of(
                        "company", company,
                        "explanation", "Regulatory explanation temporarily generated by heuristic engine. Local LLM at port 1234/8000 did not respond in time."
                )));
    }
}
